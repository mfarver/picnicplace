// Writes src/api/fingerprint.ts: the fingerprint of the OpenAPI document this Studio is
// generated from. The core reports the same fingerprint of its own document in
// /api/v1/health (core/src/picnicplace/api/fingerprint.py), so the Studio can tell when
// it is talking to a core from a different version. Run by `npm run gen:api`.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const document = readFileSync(new URL("../../docs/api/openapi.json", import.meta.url), "utf8");
const fingerprint = createHash("sha256").update(document).digest("hex").slice(0, 16);
writeFileSync(
  new URL("../src/api/fingerprint.ts", import.meta.url),
  "// Generated by scripts/api-fingerprint.mjs from docs/api/openapi.json. Do not edit.\n" +
    `export const API_FINGERPRINT = "${fingerprint}";\n`,
);
